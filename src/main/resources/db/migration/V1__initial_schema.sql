CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    description VARCHAR(2000),
    city VARCHAR(120) NOT NULL,
    venue VARCHAR(180) NOT NULL,
    starts_at TIMESTAMP NOT NULL,
    seat_rows INTEGER NOT NULL,
    seats_per_row INTEGER NOT NULL,
    seat_price DECIMAL(10, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_event_city_starts_at ON event(city, starts_at);

CREATE TABLE seat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    row_label VARCHAR(10) NOT NULL,
    seat_number INTEGER NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_seat_event FOREIGN KEY (event_id) REFERENCES event(id),
    CONSTRAINT uq_seat_event_location UNIQUE (event_id, row_label, seat_number)
);

CREATE INDEX idx_seat_event_status ON seat(event_id, status);

CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_amount DECIMAL(10, 2) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_booking_event FOREIGN KEY (event_id) REFERENCES event(id)
);

CREATE INDEX idx_booking_user_created ON booking(user_id, created_at);
CREATE INDEX idx_booking_status_expiry ON booking(status, expires_at);

CREATE TABLE booking_seat (
    booking_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL UNIQUE,
    price DECIMAL(10, 2) NOT NULL,
    PRIMARY KEY (booking_id, seat_id),
    CONSTRAINT fk_booking_seat_booking FOREIGN KEY (booking_id) REFERENCES booking(id),
    CONSTRAINT fk_booking_seat_seat FOREIGN KEY (seat_id) REFERENCES seat(id)
);

CREATE TABLE idempotency_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    idempotency_key VARCHAR(120) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    booking_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_idempotency_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_idempotency_booking FOREIGN KEY (booking_id) REFERENCES booking(id),
    CONSTRAINT uq_idempotency_user_key UNIQUE (user_id, idempotency_key)
);
